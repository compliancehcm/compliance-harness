#!/usr/bin/env node
/**
 * Cut the design system's React components out of `design-system/_ds_bundle.js`
 * into `theme/ds-components.js`, the script an artifact can opt into.
 *
 * The shipped bundle is the DS's own compiled output: one IIFE with a section
 * per source file (`// components/core/Button.jsx`, …), then the Portal do
 * Trabalhador UI kit (`// ui_kits/…` — screens and mock data), then the export
 * table. An artifact wants the primitives, not a demo portal with fake
 * holerites, so this keeps every `components/` section and every `components`
 * export and drops the rest. It also adds the short alias `window.ComplianceDS`.
 *
 * Re-run after swapping the design-system folder:
 *
 *   node plugins/compliance-brand/scripts/build-components.mjs
 *
 * The smoke test fails when the committed output is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const BUNDLE = fileURLToPath(new URL('../design-system/_ds_bundle.js', import.meta.url))
const OUTPUT = fileURLToPath(new URL('../theme/ds-components.js', import.meta.url))

/**
 * Build the components-only script from the bundle text.
 * @param bundle - `_ds_bundle.js` contents.
 * @returns the script text.
 * @throws {Error} when the bundle does not have the expected shape.
 */
export function buildComponents(bundle) {
  const header = /^\/\* @ds-bundle: (\{.*\}) \*\/\n/.exec(bundle)
  if (header === null) throw new Error('_ds_bundle.js: missing the @ds-bundle header')
  const meta = JSON.parse(header[1])
  const namespace = meta.namespace
  if (typeof namespace !== 'string' || !/^[A-Za-z_$][\w$]*$/.test(namespace)) {
    throw new Error('_ds_bundle.js: the header names no usable namespace')
  }
  const components = meta.components.filter(c => c.sourcePath.startsWith('components/')).map(c => c.name)

  const lines = bundle.slice(header[0].length).split('\n')
  const kitStart = lines.findIndex(line => line.startsWith('// ui_kits/'))
  const exportsStart = lines.findIndex(line => /^__ds_ns\.[A-Za-z]+ = __ds_scope\./.test(line))
  if (kitStart === -1 || exportsStart === -1 || exportsStart < kitStart) {
    throw new Error('_ds_bundle.js: cannot find the ui_kits and export sections')
  }
  const body = lines.slice(0, kitStart).join('\n').trimEnd()
  const exported = new Set(components)
  const exportLines = lines.slice(exportsStart)
    .filter(line => {
      const match = /^__ds_ns\.([A-Za-z]+) = __ds_scope\./.exec(line)
      return match === null ? line.trim() !== '' : exported.has(match[1])
    })
  const tail = exportLines.join('\n').replace(/\}\)\(\);\s*$/, '')
  for (const name of components) {
    if (!tail.includes(`__ds_ns.${name} = `)) throw new Error(`_ds_bundle.js: component ${name} is not exported`)
  }
  return `/* Compliance HCM Design System — React components (generated by
   plugins/compliance-brand/scripts/build-components.mjs from
   design-system/_ds_bundle.js; do not edit). Needs a global React 18.
   Exposes window.${namespace} and the alias window.ComplianceDS. */
${body}

${tail.trimEnd()}

window.ComplianceDS = __ds_ns;
})();
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = buildComponents(readFileSync(BUNDLE, 'utf8'))
  writeFileSync(OUTPUT, out)
  console.log(`wrote ${OUTPUT} (${out.length} bytes)`)
}
